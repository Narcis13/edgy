#!/usr/bin/env bash
# Regenerates the accounts evidence in this folder from fresh servers with empty data:
#   TMPDIR=/tmp/ev CHROME=/path/to/chrome docs/showcase/accounts/shoot.sh
# Builds, starts edgy on port 8792 in accounts mode, seeds three people (seed.mjs), then
# drives sign-in, the profile, sharing with people, two people in one document at once,
# a viewer, access taken away, and a server in local mode (port 8793). What each step
# printed goes to auth.txt and together.txt; screenshots next to them.
# Sync has its own script (sync.sh: the real Turso database), and so do MCP (mcp-check.mjs)
# and the upgrade of an old database (migration.sh).
set -uo pipefail
cd "$(git rev-parse --show-toplevel)"
S=goal-loop/scripts
P=.claude/goal-loop
export CDP_PANE=".desk, .home, .records, .profile"
OUT=docs/showcase/accounts
WORK="${TMPDIR:-/tmp}/accounts-shots"
PORT=8792
URL="http://127.0.0.1:$PORT"
rm -rf "$WORK"; mkdir -p "$WORK"
EDGY_AUTH=accounts bash $P/serve.sh fresh $PORT "$WORK/data" >/dev/null || exit 1

shot() { node $S/cdp.mjs shot "$@" | grep -v '^OK'; echo "   (exit ${PIPESTATUS[0]})"; }
say() { echo; echo "── $* ──"; }
# A request as someone: as <cookie|-> <method> <path> [json]
as() { local c=$1 m=$2 p=$3; shift 3; curl -s -X "$m" "$URL$p" ${c:+-H "cookie: $c"} -H 'content-type: application/json' ${1:+-d "$1"}; }
js() { node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{const v=JSON.parse(s);console.log(eval(process.argv[1]))})' "$1"; }
# Set a React-controlled field's value and tell React, from --js.
SETV='const setv = (el, v) => { Object.getOwnPropertyDescriptor(Object.getPrototypeOf(el), "value").set.call(el, v); el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true })); }; const wait = (ms) => new Promise((r) => setTimeout(r, ms));'
# In the editor: a cell by its name, and wait until a test is true.
CELL='const cell = (n) => { let f = null; const walk = (c) => { if (c.name === n) f = c; (c.children || []).forEach(walk); }; walk(edgy.state.doc.root); return f; }; const until = async (ok, ms = 8000) => { const t = Date.now(); while (!ok() && Date.now() - t < ms) await new Promise((r) => setTimeout(r, 20)); return ok(); };'

eval "$(node $OUT/seed.mjs "$URL")"

{
echo "Evidence for accounts, regenerated by shoot.sh on $(date -u +%Y-%m-%dT%H:%MZ) against a fresh server with empty data (accounts mode)."
echo "Seeded (seed.mjs): Ana Pop owns Team offsite ($OFFSITE, Ben Ortiz can edit) and Quote ($QUOTE, Cleo Diaz can view); Ben's quotes ($BENS)."

# ───────────────────────── signing in ─────────────────────────

say "A1 sign-in and sign-up, desktop, phone, dark"
shot "$URL/signin" $OUT/signin.png --size 1440x900 --cookie none
shot "$URL/signin" $OUT/signin-phone.png --size 390x844 --mobile --cookie none
shot "$URL/signup" $OUT/signup-dark.png --size 1440x900 --dark --cookie none
shot "$URL/signup" $OUT/signup-phone.png --size 390x844 --mobile --cookie none

say "A1 a wrong password: a clear message (the 401 below is that answer, expected)"
shot "$URL/signin" $OUT/wrong-password.png --size 1440x900 --cookie none --js "$SETV
  setv(document.querySelector('input[name=email]'), 'ana@example.test');
  setv(document.querySelector('input[type=password]'), 'not her password');
  document.querySelector('.auth-submit').click(); await wait(1500);
  document.querySelector('.auth-error')?.textContent"

say "A1 repeated failures are slowed down (five wrong tries, then the right one)"
for i in 1 2 3 4 5; do
  t=$(date +%s%3N); code=$(curl -s -o "$WORK/try.json" -w '%{http_code}' -XPOST "$URL/api/auth/signin" -H 'content-type: application/json' -d '{"email":"ben@example.test","password":"wrong wrong"}')
  echo "  try $i: $code in $(( $(date +%s%3N) - t )) ms  $(cat "$WORK/try.json")"
done
code=$(curl -s -o "$WORK/try.json" -w '%{http_code}' -XPOST "$URL/api/auth/signin" -H 'content-type: application/json' -d '{"email":"ben@example.test","password":"correct horse"}')
echo "  the right password now: $code $(cat "$WORK/try.json")"
# In the browser: one more wrong try (the wait has run out by now, so it counts and the wait doubles), then another at once.
# (The 401 and 429 lines below are those answers, expected.)
shot "$URL/signin" $OUT/slowed.png --size 1440x900 --cookie none --js "$SETV
  setv(document.querySelector('input[name=email]'), 'ben@example.test');
  setv(document.querySelector('input[type=password]'), 'still wrong');
  document.querySelector('.auth-submit').click(); await wait(700);
  document.querySelector('.auth-submit').click(); await wait(1200);
  [document.querySelector('.auth-error')?.textContent, document.querySelector('.auth-submit').textContent.trim(), document.querySelector('.auth-submit').disabled]"

say "A1 the session cookie and the stored password"
curl -si -XPOST "$URL/api/auth/signin" -H 'content-type: application/json' -d '{"email":"cleo@example.test","password":"correct horse"}' | tr -d '\r' | grep -i '^set-cookie' | sed -E 's/edgy_session=[^;]+/edgy_session=<43 characters>/; s/^/  /'
node -e "const {DatabaseSync}=require('node:sqlite');const db=new DatabaseSync(process.argv[1],{readOnly:true});for(const r of db.prepare('SELECT email, password FROM users ORDER BY created_at').all())console.log('  '+r.email+': '+r.password.split('\$').slice(0,4).join('\$')+'\$<16-byte salt>\$<32-byte hash>  ('+r.password.length+' characters, no password in it)');const s=db.prepare('SELECT hash FROM sessions LIMIT 1').get();console.log('  sessions are kept as a digest: '+s.hash.length+' characters of SHA-256, base64url')" "$WORK/data/edgy.db"

say "A2 signed out: pages lead to sign-in (and back), the API answers 401"
shot "$URL/d/$OFFSITE" $OUT/signed-out.png --size 1440x900 --cookie none --js "[location.pathname + location.search, document.querySelector('h1')?.textContent]"
for p in /api/docs /api/library /api/data /api/docs/$OFFSITE /api/docs/$OFFSITE/events /api/me /api/sync /api/guide; do
  echo "  GET $p → $(curl -s -o /dev/null -w '%{http_code}' "$URL$p")"
done
echo "  GET /api/health → $(curl -s "$URL/api/health")"
shot "$URL/signin?next=%2Fd%2F$OFFSITE" $OUT/signed-in-back.png --size 1440x900 --cookie none --js "$SETV
  setv(document.querySelector('input[name=email]'), 'ana@example.test');
  setv(document.querySelector('input[type=password]'), 'correct horse');
  document.querySelector('.auth-submit').click(); await wait(3500); location.pathname"

# ───────────────────────── the library, people, the profile ─────────────────────────

say "Mine and Shared with me"
shot "$URL/?scope=mine" $OUT/library-ana.png --size 1440x900 --cookie "$ANA"
shot "$URL/?scope=shared" $OUT/shared-with-me-ben.png --size 1440x900 --cookie "$BEN"
shot "$URL/?scope=shared" $OUT/shared-with-me-phone.png --size 390x844 --mobile --cookie "$CLEO"

say "C1 the Share dialog: people, desktop and phone"
shot "$URL/d/$OFFSITE?view=edit" $OUT/share-people.png --size 1440x900 --cookie "$ANA" --js "document.querySelector('.share-btn').click(); await new Promise((r) => setTimeout(r, 1200)); [...document.querySelectorAll('.people-row, .pp-row, [class*=people] li')].length"
shot "$URL/d/$QUOTE?view=live" $OUT/share-people-phone.png --size 390x844 --mobile --cookie "$ANA" --js "document.querySelector('.more-btn').click(); await new Promise((r) => setTimeout(r, 300)); [...document.querySelectorAll('.more-menu [role=menuitem]')].find((b) => /Share/.test(b.textContent)).click(); await new Promise((r) => setTimeout(r, 1200)); 'opened'"

say "P1 the profile; a key shown once; deleting asks first"
shot "$URL/profile" $OUT/profile.png --size 1440x900 --cookie "$ANA" --full
shot "$URL/profile" $OUT/profile-phone.png --size 390x844 --mobile --cookie "$BEN"
shot "$URL/profile" $OUT/key-created.png --size 1440x900 --cookie "$BEN" --js "$SETV
  const name = [...document.querySelectorAll('input')].find((i) => /laptop|key/i.test(i.placeholder || ''));
  setv(name, 'Ben’s scripts'); [...document.querySelectorAll('button')].find((b) => b.textContent.trim() === 'Create key').click(); await wait(1200);
  const shown = [...document.querySelectorAll('input, textarea, code')].find((e) => /^edgy_/.test(e.value || e.textContent || ''));
  shown?.scrollIntoView({ block: 'center' }); await wait(300); 'shown once: ' + !!shown"
shot "$URL/profile" $OUT/delete-dialog.png --size 1440x900 --cookie "$BEN" --js "[...document.querySelectorAll('button')].find((b) => /Delete account/.test(b.textContent)).click(); await new Promise((r) => setTimeout(r, 600)); document.querySelector('[role=dialog]')?.textContent.slice(0, 160)"
echo "  deleting without the password: $(as "$BEN" DELETE /api/me '{"password":"guess"}')"

} 2>&1 | tee "$OUT/auth.txt"

# ───────────────────────── two people in one document ─────────────────────────

{
echo "Two people in one document, regenerated by shoot.sh on $(date -u +%Y-%m-%dT%H:%MZ)."
echo "Ana (owner) and Ben (editor) open Team offsite at once, each in a browser of their own. Ben selects 'left' (still to spend), Ana"
echo "selects the calendar; at the same moment Ana sets the budget and Ben sets the head count."
T=$(( $(date +%s%3N) + 11000 ))
# Each page: select a cell, wait for the agreed moment, make one edit, then time how long the other's edit takes to show.
node $S/cdp.mjs shot "$URL/d/$OFFSITE?view=edit" $OUT/together-ben.png --size 1440x900 --cookie "$BEN" --wait 4000 --js "$CELL
  edgy.select(cell('left').id);
  while (Date.now() < $T) await new Promise((r) => setTimeout(r, 5));
  const t0 = Date.now(); edgy.dispatch(['set', cell('people').id, 'value', 20]);
  const ok = await until(() => cell('budget').value === 18000);
  const seen = Date.now();
  await new Promise((r) => setTimeout(r, 2500));
  JSON.stringify({ who: 'Ben', sent: t0, sawOther: ok ? seen : null })" > "$WORK/ben.out" 2>&1 &
node $S/cdp.mjs shot "$URL/d/$OFFSITE?view=edit" $OUT/together-ana.png --size 1440x900 --cookie "$ANA" --wait 4000 --js "$CELL
  edgy.select(cell('cal').id);
  while (Date.now() < $T) await new Promise((r) => setTimeout(r, 5));
  const t0 = Date.now(); edgy.dispatch(['set', cell('budget').id, 'value', 18000]);
  const ok = await until(() => cell('people').value === 20);
  const seen = Date.now();
  await new Promise((r) => setTimeout(r, 2500));
  JSON.stringify({ who: 'Ana', sent: t0, sawOther: ok ? seen : null })" > "$WORK/ana.out" 2>&1
wait
grep -h '^JS\|CONSOLE' "$WORK/ana.out" "$WORK/ben.out" | sed 's/^/  /'
node -e "
  const fs=require('fs');const get=(f)=>JSON.parse(JSON.parse(fs.readFileSync(f,'utf8').split('\n').find(l=>l.startsWith('JS')).slice(3)));
  const a=get(process.argv[1]), b=get(process.argv[2]);
  console.log('  Ana\'s edit reached Ben\'s screen in '+(b.sawOther-a.sent)+' ms; Ben\'s reached Ana\'s in '+(a.sawOther-b.sent)+' ms (both under a second: '+(b.sawOther-a.sent<1000&&a.sawOther-b.sent<1000)+')');
" "$WORK/ana.out" "$WORK/ben.out"
echo "  both edits survived: $(as "$ANA" GET /api/docs/$OFFSITE/read | js '`budget ${v.values.budget}, people ${v.values.people}`')"
echo "  Activity, as stored (newest last): $(as "$ANA" GET "/api/docs/$OFFSITE/log?limit=6" | js 'v.map(e=>e.actor.kind==="agent"?`${e.actor.name} for ${e.actor.for}`:e.actor.name).join(", ")')"

echo
echo "P1 Ana renames herself: presence and Activity show the new name."
as "$ANA" PATCH /api/me '{"name":"Ana Maria Pop"}' >/dev/null
shot "$URL/d/$OFFSITE?view=edit" $OUT/renamed.png --size 1440x900 --cookie "$BEN" --js "await new Promise((r) => setTimeout(r, 800)); [...document.querySelectorAll('.activity b, .act-who, .chip')].map((e) => e.textContent.trim()).filter((t) => /Ana/.test(t)).slice(0, 4)"

echo
echo "A3 Cleo can view the quote, not change it; then Ana takes that away while Cleo has it open."
shot "$URL/d/$QUOTE" $OUT/viewer.png --size 1440x900 --cookie "$CLEO"
echo "  Cleo posts an op: $(as "$CLEO" POST /api/docs/$QUOTE/ops '{"ops":[["set","valid","value",60]]}')"
( sleep 6; as "$ANA" DELETE /api/docs/$QUOTE/people/$CLEO_ID >/dev/null ) &
shot "$URL/d/$QUOTE" $OUT/revoked.png --size 1440x900 --cookie "$CLEO" --wait 9000 --js "document.body.innerText.slice(0, 120)"
wait
echo "  afterwards: GET the quote as Cleo → $(curl -s -o /dev/null -w '%{http_code}' -H "cookie: $CLEO" "$URL/api/docs/$QUOTE")"
} 2>&1 | tee "$OUT/together.txt"

# ───────────────────────── local mode ─────────────────────────

{
echo
echo "L0 local mode (EDGY_AUTH=local, how npm run dev starts): no sign-in on this machine."
EDGY_AUTH=local bash $P/serve.sh fresh 8793 "$WORK/local" >/dev/null || exit 1
shot "http://127.0.0.1:8793/" $OUT/local-mode.png --size 1440x900 --cookie none --js "document.querySelector('.um-btn')?.click(); await new Promise((r) => setTimeout(r, 400)); document.querySelector('.um-who')?.textContent"
echo "  without a key, as before: GET /api/docs → $(curl -s http://127.0.0.1:8793/api/docs | js 'v.map(d=>d.title).join(", ")')"
echo "  a page that rebinds its name to this machine is not this machine: GET /api/me with Host: evil.example → $(curl -s -o /dev/null -w '%{http_code}' -H 'host: evil.example' http://127.0.0.1:8793/api/me)"
bash $P/serve.sh stop 8793 >/dev/null
} 2>&1 | tee -a "$OUT/auth.txt"

bash $P/serve.sh stop $PORT >/dev/null
