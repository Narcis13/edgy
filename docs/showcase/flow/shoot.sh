#!/usr/bin/env bash
# Regenerates the Flow evidence in this folder from a fresh server with empty data:
#   TMPDIR=/tmp/ev CHROME=/path/to/chrome docs/showcase/flow/shoot.sh
# Builds, starts edgy on port 8792 in accounts mode, seeds Ana Pop's fortnight (seed.mjs: notes, tasks,
# events, comments and reactions by her and by Claude with her key, a running clock, two documents), then
# shoots every view at desktop and phone size, light and dark, and drives the interactions: a reaction
# toggled, a comment sent, a card dragged and moved with the keyboard, a column renamed, a task ticked and
# re-dated, a day clicked on the calendar, a note edited in place, the composer's preview, the clock stopped,
# an agent's post arriving live, the dashboard document reading it all. What each step found goes to checks.txt.
set -uo pipefail
cd "$(git rev-parse --show-toplevel)"
S=goal-loop/scripts
P=.claude/goal-loop
export CDP_PANE=".home, .desk"
OUT=docs/showcase/flow
WORK="${TMPDIR:-/tmp}/flow-shots"
PORT=8792
URL="http://127.0.0.1:$PORT"
rm -rf "$WORK"; mkdir -p "$WORK"
EDGY_AUTH=accounts bash $P/serve.sh fresh $PORT "$WORK/data" >/dev/null || exit 1

shot() { node $S/cdp.mjs shot "$@" | grep -v '^OK\|^REQUESTS'; echo "   (exit ${PIPESTATUS[0]})"; }
say() { echo; echo "── $* ──"; }
as() { local c=$1 m=$2 p=$3; shift 3; curl -s -X "$m" "$URL$p" -H "cookie: $c" -H "origin: $URL" -H 'content-type: application/json' ${1:+-d "$1"}; }
SETV='const setv = (el, v) => { Object.getOwnPropertyDescriptor(Object.getPrototypeOf(el), "value").set.call(el, v); el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true })); }; const wait = (ms) => new Promise((r) => setTimeout(r, ms)); const post = (t) => document.querySelector(`.post[aria-label="${t}"]`); const flow = async () => (await fetch("/api/flow")).json();'
PTR='const ptr = (el, type, x, y) => el.dispatchEvent(new PointerEvent(type, { bubbles: true, cancelable: true, clientX: x, clientY: y, pointerId: 1, pointerType: "mouse", button: 0, buttons: type === "pointerup" ? 0 : 1, isPrimary: true })); const mid = (el) => { const r = el.getBoundingClientRect(); return [r.left + r.width / 2, r.top + r.height / 2]; };'

eval "$(node $OUT/seed.mjs "$URL")"
export CDP_COOKIE="$ANA_COOKIE"

{
echo "Evidence for Flow, regenerated by shoot.sh on $(date -u +%Y-%m-%dT%H:%MZ) against a fresh server with empty data (accounts mode)."
echo "Seeded (seed.mjs): Ana Pop's fortnight; Claude with her API key; the dashboard document $DASH; the draft $DRAFT."

say "F1 F13 the five views: desktop, phone, dark"
shot "$URL/flow" $OUT/timeline.png --size 1440x900
shot "$URL/flow" $OUT/timeline-full.png --size 1440x900 --full
shot "$URL/flow" $OUT/timeline-dark.png --size 1440x900 --dark --js "document.querySelector('.home').scrollTop = 700; 'scrolled'"
shot "$URL/flow" $OUT/phone-timeline.png --size 390x844 --mobile
shot "$URL/flow?view=board" $OUT/board.png --size 1440x900
shot "$URL/flow?view=board" $OUT/board-dark.png --size 1440x900 --dark
shot "$URL/flow?view=board" $OUT/phone-board.png --size 390x844 --mobile
shot "$URL/flow?view=tasks" $OUT/tasks.png --size 1440x900 --full
shot "$URL/flow?view=tasks" $OUT/phone-tasks.png --size 390x844 --mobile
shot "$URL/flow?view=calendar" $OUT/calendar-month.png --size 1440x900 --full
shot "$URL/flow?view=calendar" $OUT/calendar-week.png --size 1440x900 --js "document.querySelector('.cal-toolbar .seg button:last-child').click(); await new Promise((r) => setTimeout(r, 300)); document.querySelector('.cal-week') ? 'week' : 'no week'"
shot "$URL/flow?view=calendar" $OUT/calendar-week-dark.png --size 1440x900 --dark --js "document.querySelector('.cal-toolbar .seg button:last-child').click(); await new Promise((r) => setTimeout(r, 300)); 'week'"
shot "$URL/flow?view=calendar" $OUT/phone-calendar.png --size 390x844 --mobile
shot "$URL/flow?view=notes" $OUT/notes.png --size 1440x900 --full
shot "$URL/flow?view=notes" $OUT/notes-dark.png --size 1440x900 --dark
shot "$URL/flow?view=notes" $OUT/phone-notes.png --size 390x844 --mobile

say "F1 filters and search: Tasks only, then the words 'ledger' (a comment) and the tag #sales"
shot "$URL/flow" $OUT/timeline-filter.png --size 1440x900 --js "$SETV
  [...document.querySelectorAll('.flow-filters .lib-chip')].find((b) => b.textContent === 'Tasks').click(); await wait(200);
  document.querySelector('.flow-today').scrollIntoView(); document.querySelector('.home').scrollTop -= 60;
  const tasks = document.querySelectorAll('.post').length;
  setv(document.querySelector('.flow-search input'), 'ledger'); await wait(200); const found = [...document.querySelectorAll('.post')].map((p) => p.getAttribute('aria-label'));
  setv(document.querySelector('.flow-search input'), ''); [...document.querySelectorAll('.flow-filters .lib-chip')].find((b) => b.textContent === 'All').click();
  [...document.querySelectorAll('.flow-tagrow .flow-tag')].find((b) => b.textContent.startsWith('#sales')).click(); await wait(200);
  [tasks, found, document.querySelectorAll('.post').length]"

say "F2 reactions toggle: like once (count 1, mine), love, then like again (gone)"
shot "$URL/flow" $OUT/reactions.png --size 1440x900 --js "$SETV
  const p = post('Pay the invoice'); p.scrollIntoView(); const like = p.querySelector('.post-reaction[aria-label^=Like]');
  like.click(); await wait(600); const once = [like.getAttribute('aria-label'), like.getAttribute('aria-pressed')];
  p.querySelector('.post-reaction[aria-label^=Love]').click(); await wait(600);
  like.click(); await wait(600);
  [once, like.getAttribute('aria-label'), like.getAttribute('aria-pressed'), (await flow()).reactions.filter((r) => r.item === p.dataset.id).length]"
say "F2 a comment: Enter sends it; the post shows it and moves to the top"
shot "$URL/flow" $OUT/comments.png --size 1440x900 --js "$SETV
  const p = post('Book the offsite venue'); const ta = p.querySelector('.post-write-text'); setv(ta, 'Venue shortlist: the lighthouse or the mill.');
  ta.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true })); await wait(800);
  const again = post('Book the offsite venue'); again.scrollIntoView({ block: 'center' });
  [again.querySelectorAll('.post-comment').length, again.querySelector('.post-comments-n').textContent, document.querySelector('.flow-day .post').getAttribute('aria-label')]"
say "F2 F11 the agent's post, comment and reaction show as the agent's (pink, 'for Ana Pop')"
shot "$URL/flow" $OUT/agent-post.png --size 1440x900 --js "$SETV const p = post('Reply to the three new leads'); p.scrollIntoView(); document.querySelector('.home').scrollTop -= 40; [p.classList.contains('is-agent'), p.querySelector('.flow-who-name').textContent, p.querySelector('.post-comment.is-agent') !== null]"

say "F3 the board: a drag held over Doing shows the ghost and the drop line"
shot "$URL/flow?view=board" $OUT/board-drag.png --size 1440x900 --js "$SETV $PTR
  const card = document.querySelector('.board-card[data-id=$VENUE]'); const [x, y] = mid(card);
  ptr(card, 'pointerdown', x, y); ptr(card, 'pointermove', x + 6, y + 2); ptr(window, 'pointermove', x + 6, y + 2);
  const doing = document.querySelector('.board-col[data-column=Doing]'); const [dx, dy] = mid(doing);
  ptr(card, 'pointermove', dx, dy - 120); ptr(window, 'pointermove', dx, dy - 120); await wait(200);
  [!!document.querySelector('.board-ghost'), !!document.querySelector('.board-drop'), document.querySelector('.board-col.is-over')?.dataset.column]"
say "F3 the whole drag: Book the offsite venue lands in Doing (status Doing, not done)"
shot "$URL/flow?view=board" $OUT/board-after.png --size 1440x900 --js "$SETV $PTR
  const card = document.querySelector('.board-card[data-id=$VENUE]'); const [x, y] = mid(card);
  ptr(card, 'pointerdown', x, y); ptr(card, 'pointermove', x + 6, y + 2); ptr(window, 'pointermove', x + 6, y + 2);
  const doing = document.querySelector('.board-col[data-column=Doing]'); const [dx, dy] = mid(doing);
  ptr(card, 'pointermove', dx, dy - 120); ptr(window, 'pointermove', dx, dy - 120); await wait(100); ptr(card, 'pointerup', dx, dy - 120); ptr(window, 'pointerup', dx, dy - 120); await wait(800);
  const it = (await flow()).items.find((i) => i.id === '$VENUE'); [it.status, it.done, document.querySelector('.board-col[data-column=Doing] .board-card[data-id=$VENUE]') !== null]"
say "F3 F14 keyboard: Shift+ArrowRight moves the focused card to Done (done true), Shift+ArrowLeft back; focus stays on it"
shot "$URL/flow?view=board" $OUT/board-keys.png --size 1440x900 --js "$SETV
  const key = (k) => document.querySelector('.board-card[data-id=$VENUE]').dispatchEvent(new KeyboardEvent('keydown', { key: k, shiftKey: true, bubbles: true }));
  document.querySelector('.board-card[data-id=$VENUE]').focus(); key('ArrowRight'); await wait(800); const a = (await flow()).items.find((i) => i.id === '$VENUE');
  key('ArrowLeft'); await wait(800); const b = (await flow()).items.find((i) => i.id === '$VENUE');
  [[a.status, a.done], [b.status, b.done], document.activeElement?.dataset?.id === '$VENUE']"
say "F3 columns: Doing renamed Now with rename (its cards follow), a column added, then back to Inbox · Doing · Done"
as "$ANA_COOKIE" PUT /api/flow/board '{"columns":["Inbox","Now","Review","Done"],"rename":{"from":"Doing","to":"Now"}}'; echo
shot "$URL/flow?view=board" $OUT/board-columns.png --size 1440x900 --js "[...document.querySelectorAll('.board-col')].map((c) => c.dataset.column + ':' + c.querySelectorAll('.board-card').length)"
as "$ANA_COOKIE" PUT /api/flow/board '{"columns":["Inbox","Doing","Done"],"rename":{"from":"Now","to":"Doing"}}' >/dev/null

say "F4 tasks: ticking 'Prepare the demo' finishes it (Done grows); the due day of 'Read the Hono docs' set with the date field"
shot "$URL/flow?view=tasks" $OUT/tasks-tick.png --size 1440x900 --js "$SETV
  const row = [...document.querySelectorAll('.tasks-row')].find((r) => r.textContent.includes('Prepare the demo')); row.querySelector('.flow-done input').click(); await wait(700);
  const hono = [...document.querySelectorAll('.tasks-row')].find((r) => r.textContent.includes('Read the Hono docs')); hono.querySelector('.tasks-due').click(); await wait(200);
  setv(hono.querySelector('input[type=date]'), '$(date -d '+8 days' +%F 2>/dev/null || date -v+8d +%F)'); await wait(700);
  const r = await flow(); [r.items.find((i) => i.text === 'Prepare the demo').done, r.items.find((i) => i.text.startsWith('Read the Hono')).due, document.querySelector('.tasks-group[data-bucket=done] summary')?.textContent.trim()]"

say "F5 calendar: clicking a day opens the editor for a new event on that day"
shot "$URL/flow?view=calendar" $OUT/calendar-click.png --size 1440x900 --js "$SETV
  const day = [...document.querySelectorAll('.cal-day:not(.is-out)')].find((d) => d.dataset.day > '$(date +%F)' && !d.querySelector('.cal-chip')); day.click(); await wait(400);
  const d = document.querySelector('dialog.flow-dialog'); [d?.open, d?.querySelector('h2')?.textContent, d?.querySelector('input[type=date]')?.value === day.dataset.day]"

say "F6 notes: click a card, change the title, Esc: saved in place; 'Make it a task' from the menu puts it on the board"
shot "$URL/flow?view=notes" $OUT/notes-edit.png --size 1440x900 --js "$SETV
  const card = document.querySelector('.note-card[data-id=$WHY]'); card.click(); await wait(300);
  setv(card.querySelector('textarea'), 'Why one timeline? (edited)'); card.querySelector('textarea').dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true })); await wait(700);
  const r = await flow(); [r.items.find((i) => i.id === '$WHY').text, document.querySelector('.note-card.is-editing') === null]"
as "$ANA_COOKIE" PATCH /api/flow/$READING '{"kind":"task"}' | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{const i=JSON.parse(s);console.log("  Reading list made a task: kind", i.kind, "status", i.status)})'
as "$ANA_COOKIE" PATCH /api/flow/$READING '{"kind":"note"}' >/dev/null

say "F7 the composer: what quick-add understood, then Post makes the event"
shot "$URL/flow" $OUT/composer.png --size 1440x900 --js "$SETV setv(document.querySelector('.flow-composer-text'), 'Call Ben tomorrow 3pm-4pm #sales !!'); await wait(100); document.querySelector('.flow-preview').textContent"
shot "$URL/flow" $OUT/composer-posted.png --size 1440x900 --js "$SETV
  setv(document.querySelector('.flow-composer-text'), 'Plan the week friday 9am for 30m #team'); await wait(100); document.querySelector('.flow-post').click(); await wait(900);
  const it = (await flow()).items.find((i) => i.text === 'Plan the week'); [it?.kind, it?.start?.slice(10), it?.end?.slice(10), it?.tags, document.querySelector('.flow-day .post')?.getAttribute('aria-label')]"
say "F7 the clock: Today shows it running; Stop keeps the minutes (40 logged + 25 running) and comments"
shot "$URL/flow" $OUT/today.png --size 1440x900 --js "document.querySelector('.flow-today-item.is-running .flow-today-side').textContent"
shot "$URL/flow" $OUT/clock.png --size 1440x900 --js "$SETV
  document.querySelector('.flow-today-item.is-running .btn').click(); await wait(900); const r = await flow(); const it = r.items.find((i) => i.id === '$BADGE');
  post('Fix the sync badge on phones')?.scrollIntoView({ block: 'center' });
  [it.clock, it.spent, r.comments.filter((c) => c.item === '$BADGE').map((c) => c.text)]"

say "F8 the item editor from a post: kind, text, tags, column, due, start and end, priority, pinned, the attached document"
shot "$URL/flow" $OUT/item-editor.png --size 1440x900 --js "$SETV post('Write the launch post').querySelector('.post-text').click(); await wait(400); const d = document.querySelector('dialog.flow-dialog'); [d?.querySelector('h2')?.textContent, d?.querySelector('select')?.value, [...d.querySelectorAll('select')].at(-1)?.selectedOptions[0]?.textContent]"
shot "$URL/flow" $OUT/phone-item-editor.png --size 390x844 --mobile --js "$SETV post('Write the launch post').querySelector('.post-text').click(); await wait(400); document.querySelector('dialog.flow-dialog')?.open"

say "F12 live: an agent posts over HTTP with the key while the timeline is open; the post appears, as the agent's, without a reload"
shot "$URL/flow" $OUT/live.png --size 1440x900 --js "$SETV
  const before = document.querySelectorAll('.post').length;
  const res = await fetch('/api/flow', { method: 'POST', headers: { 'content-type': 'application/json', authorization: 'Bearer $CLAUDE_KEY' }, body: JSON.stringify({ text: 'I finished the ledger check: everything matches. #finance', actor: { kind: 'agent', name: 'Claude' } }) });
  await wait(1500); const first = document.querySelector('.flow-day .post');
  [res.status, before, document.querySelectorAll('.post').length, first.getAttribute('aria-label'), first.classList.contains('is-agent')]"
say "F12 a document's insert! lands in the same collection and is heard the same way (POST /api/data/flow, then the DOM)"
shot "$URL/flow" $OUT/live-record.png --size 1440x900 --js "$SETV
  await fetch('/api/data/flow', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ record: { kind: 'task', text: 'Saved by a document' } }) });
  await wait(1500); [...document.querySelectorAll('.post')].some((p) => p.getAttribute('aria-label') === 'Saved by a document')"

say "F11 edgy_flow over MCP (list, post, react) through mcp-check.mjs"
EDGY_URL="$URL" EDGY_API_KEY="$CLAUDE_KEY" node $OUT/mcp-check.mjs

say "F9 the dashboard document reads the Flow: values from GET /read, then the page"
curl -s "$URL/api/docs/$DASH/read" -H "cookie: $ANA_COOKIE" | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{const r=JSON.parse(s);const v=r.values||{};console.log("  open-n", v["open-n"], "overdue-n", v["overdue-n"], "done-n", v["done-n"], "minutes", v["minutes"], "errors", JSON.stringify(r.errors||{}))})'
shot "$URL/d/$DASH?view=live" $OUT/dashboard.png --size 1440x900 --full --pane ".desk"
say "F9 the Done button in the dashboard's table changes the record (done: true); the board shows it in the last column by rule"
shot "$URL/d/$DASH?view=live" $OUT/dashboard-done.png --size 1440x900 --pane ".desk" --js "$SETV
  const btn = [...document.querySelectorAll('button')].find((b) => b.textContent.trim() === 'Done'); btn.click(); await wait(1200);
  const r = await flow(); const done = r.items.filter((i) => i.done); [done.length, done.map((i) => i.text)]"
say "F9 the Data page lists the Flow collections"
shot "$URL/data" $OUT/data-flow.png --size 1440x900 --js "[...document.querySelectorAll('.collections button')].map((b) => b.textContent.trim())"

say "F10 sync: src/server/sync.test.ts 'Flow travels like any record'"
npx tsx --disable-warning=ExperimentalWarning --test src/server/sync.test.ts 2>&1 | grep -E "Flow travels|^ℹ (tests|pass|fail)"
} 2>&1 | tee $OUT/checks.txt

bash $P/serve.sh stop $PORT >/dev/null
echo "done: $OUT"
