#!/usr/bin/env bash
# Regenerates the evidence in this folder from a fresh server with empty data:
#   TMPDIR=/tmp/ev CHROME=/path/to/chrome docs/showcase/library/shoot.sh
# Builds, starts edgy on port 8795, seeds the showcase library (seed.mjs), then drives
# the home page, sharing, decks and Play, and the exported files opened from disk with
# the network off. What each run printed goes to library.txt; screenshots next to it.
set -uo pipefail
cd "$(git rev-parse --show-toplevel)"
S=goal-loop/scripts
P=.claude/goal-loop
export CDP_PANE=".desk, .home, .records, .slide-room"
OUT=docs/showcase/library
WORK="${TMPDIR:-/tmp}/library-shots"
PORT=8795
URL="http://127.0.0.1:$PORT"
LOG="$OUT/library.txt"
rm -rf "$WORK"; mkdir -p "$WORK"
bash $P/serve.sh fresh $PORT "$WORK/data" >/dev/null || exit 1

shot() { node $S/cdp.mjs shot "$@" | grep -v '^OK'; echo "   (exit ${PIPESTATUS[0]})"; }
say() { echo; echo "── $* ──"; }
api() { curl -s "$URL$1" "${@:2}"; }
js() { node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{const v=JSON.parse(s);console.log(eval(process.argv[1]))})' "$1"; }
# Set a React-controlled field's value and tell React, from --js.
# A background headless tab has no focus, so focus() and blur() do nothing: send the events fields listen for.
SETV='const setv = (el, v) => { Object.getOwnPropertyDescriptor(Object.getPrototypeOf(el), "value").set.call(el, v); el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true })); }; const wait = (ms) => new Promise((r) => setTimeout(r, ms)); const focusIn = (el) => el.dispatchEvent(new FocusEvent("focusin", { bubbles: true })); const focusOut = (el) => el.dispatchEvent(new FocusEvent("focusout", { bubbles: true }));'

eval "$(node $OUT/seed.mjs "$URL")"

{
echo "Evidence for the library goal, regenerated by shoot.sh on $(date -u +%Y-%m-%dT%H:%MZ) against a fresh server with empty data."
echo "Showcase library (seed.mjs): offsite $OFFSITE, quote $QUOTE, billing $BILLING, orders $ORDERS, savings $SAVINGS, deck $DECK"

# ───────────────────────── the home page ─────────────────────────

# Find a card by its title, open its menu and pick an item; wait for the library to settle.
LIB="$SETV
  const card = (t) => [...document.querySelectorAll('.lc')].find((c) => c.querySelector('.lc-title')?.textContent.trim() === t);
  const titles = (sel = '.lib-section') => [...document.querySelectorAll(sel + ' .lc-title')].map((e) => e.textContent.trim());
  const pinned = () => titles('.lib-section.is-pinned');
  const menu = async (t, item) => { card(t).querySelector('.lc-menu-btn').click(); await wait(150); [...document.querySelectorAll('.lc-menu-list [role=menuitem]')].find((b) => b.textContent.trim() === item).click(); await wait(700); };
  const search = async (q) => { setv(document.querySelector('input[aria-label=\"Search documents\"]'), q); await wait(700); };
  const filter = async (name) => { [...document.querySelectorAll('.lib-chip')].find((b) => b.textContent.trim().startsWith(name)).click(); await wait(600); };"

say "the showcase library at desktop, phone and dark"
shot "$URL/" "$OUT/home.png" --size 1440x900 --wait 2500
shot "$URL/" "$OUT/home-phone.png" --size 390x844 --mobile --wait 2500
shot "$URL/" "$OUT/home-dark.png" --size 1440x900 --dark --wait 2500
shot "$URL/" "$WORK/home-tablet.png" --size 820x1180 --mobile --wait 2500

say "L2 search: a word only in a title, only in a description, only in a cell; nothing found; cleared"
shot "$URL/" "$OUT/search-title.png" --size 1440x900 --wait 2500 --js "(async () => { $LIB
  const out = {};
  for (const q of ['ledger', 'tablet', 'lighthouse', 'zeppelin']) { await search(q); out[q] = { found: titles(), where: [...document.querySelectorAll('.lc-match')].map((m) => m.textContent.trim().slice(0, 60)), empty: document.querySelector('.lib-empty')?.textContent.trim() ?? null }; }
  await search(''); out.cleared = document.querySelectorAll('.lc').length;
  await search('ledger'); return out; })()"
shot "$URL/" "$OUT/search-text.png" --size 1440x900 --wait 2500 --js "(async () => { $LIB await search('lighthouse'); return titles(); })()"
shot "$URL/" "$OUT/search-none.png" --size 390x844 --mobile --wait 2500 --js "(async () => { $LIB await search('zeppelin'); return document.querySelector('.lib-empty')?.textContent.trim(); })()"

say "L3 a description typed on a card survives a reload and is read and changed inside the document"
shot "$URL/" "$WORK/describe-typing.png" --size 1440x900 --wait 2500 --js "(async () => { $LIB
  card('Kick-off notes, Harbour & Co.').querySelector('.lc-add').click(); await wait(200);
  const t = document.querySelector('.lc textarea[aria-label=Description]'); setv(t, 'Notes from the first call: festival deadline, who does what.');
  t.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true })); await wait(800); return card('Kick-off notes, Harbour & Co.').querySelector('.lc-desc')?.textContent; })()"
shot "$URL/" "$OUT/describe-card.png" --size 1440x900 --wait 2500 --js "(() => { const c = [...document.querySelectorAll('.lc')].find((c) => c.textContent.includes('Kick-off')); c.scrollIntoView({ block: 'center' }); return c.querySelector('.lc-desc')?.textContent; })()"
echo "   inside the document (meta.description): $(api /api/docs/$NOTES | js 'v.meta.description')"
shot "$URL/d/$NOTES?view=edit" "$OUT/describe-inside.png" --size 1440x900 --wait 3000 --js "(async () => { $SETV
  const t = document.querySelector('.side.right textarea[aria-label=Description]'); const was = t.value; focusIn(t); setv(t, was + ' Changed inside.'); focusOut(t); await wait(1200); return { was, now: edgy.state.doc.meta.description }; })()"
echo "   after changing it inside: $(api /api/docs/$NOTES | js 'v.meta.description')"

say "L4 pinned: kept across reloads and every sort, reordered and kept, unpinned back among the rest"
shot "$URL/" "$WORK/pins.png" --size 1440x900 --wait 2500 --js "(async () => { $LIB
  const out = { first: pinned() };
  for (const v of ['created', 'title', 'updated']) { setv(document.querySelector('.lib-sort select'), v); await wait(600); out[v] = pinned(); }
  await menu('Studio billing and ledger', 'Move up'); out.movedUp = pinned(); return out; })()"
shot "$URL/" "$OUT/pinned.png" --size 1440x900 --wait 2500 --js "(async () => { $LIB return { afterReload: pinned(), sort: document.querySelector('.lib-sort select').value }; })()"
echo "   pins on the server: $(api /api/library | js 'v.pinned.map(e=>e.title).join(", ")')"
shot "$URL/" "$WORK/unpin.png" --size 1440x900 --wait 2500 --js "(async () => { $LIB await menu('Harbour & Co. order desk', 'Unpin'); return { pinned: pinned(), backInList: titles('.lib-section:not(.is-pinned)').includes('Harbour & Co. order desk') }; })()"
api /api/docs/$ORDERS -XPATCH -H 'content-type: application/json' -d '{"pinned":true}' -o /dev/null

say "L5 archive, the Archived filter, restore with content and history unchanged; delete asks first"
BEFORE="$(api /api/docs/$STALL)$(api /api/docs/$STALL/log)"
shot "$URL/" "$OUT/archived.png" --size 1440x900 --wait 2500 --js "(async () => { $LIB
  await menu('Saturday market stall', 'Archive'); const inList = titles().includes('Saturday market stall'); const toast = document.querySelector('.lib-toast')?.textContent;
  await filter('Archived'); return { inList, toast, archived: titles() }; })()"
shot "$URL/" "$WORK/restored.png" --size 1440x900 --wait 2500 --js "(async () => { $LIB await filter('Archived'); await menu('Saturday market stall', 'Restore'); await filter('All'); return titles().includes('Saturday market stall'); })()"
AFTER="$(api /api/docs/$STALL)$(api /api/docs/$STALL/log)"
[ "$BEFORE" = "$AFTER" ] && echo "   content and history after archive + restore: identical" || echo "   content and history CHANGED"
shot "$URL/" "$OUT/delete-dialog.png" --size 1440x900 --wait 2500 --js "(async () => { $LIB await filter('Archived'); await menu('Spring fair checklist', 'Delete'); return document.querySelector('dialog[open]')?.textContent.trim().slice(0, 120); })()"
shot "$URL/" "$WORK/delete.png" --size 1440x900 --wait 2500 --js "(async () => { $LIB await filter('Archived'); await menu('Spring fair checklist', 'Delete'); const asked = document.querySelector('dialog[open]')?.textContent.trim().slice(0, 80); document.querySelector('dialog[open] .btn.danger').click(); await wait(900); return { asked, left: titles() }; })()"
shot "$URL/d/$OLD" "$OUT/deleted.png" --size 1440x900 --wait 2500 --js "document.querySelector('h1')?.textContent"

say "L6 selecting several: by keyboard at desktop, by touch on a phone"
shot "$URL/" "$OUT/select-keyboard.png" --size 1440x900 --wait 2500 \
  --press "input[aria-label='Select Visitor feedback']|Space;;input[aria-label='Select Quote for Harbour & Co.']|Space" \
  --then "({ count: document.querySelector('.lib-selcount')?.textContent, actions: [...document.querySelectorAll('.lib-selbar button')].map((b) => b.textContent.trim()) })"
shot "$URL/" "$OUT/select-phone.png" --size 390x844 --mobile --wait 2500 --js "(async () => { $LIB
  for (const t of ['Visitor feedback', 'Kick-off notes, Harbour & Co.', 'Quote for Harbour & Co.']) card(t).querySelector('.lc-check').click(); await wait(400);
  const b = document.querySelector('.lib-selbar').getBoundingClientRect(); const smallest = Math.min(...[...document.querySelectorAll('.lib-selbar button, .lc-check')].map((e) => e.getBoundingClientRect().height));
  return { bar: [Math.round(b.top), Math.round(b.bottom)], smallestTarget: smallest, overflowX: document.documentElement.scrollWidth > innerWidth }; })()"

say "K1 grouping three documents makes a deck card"
shot "$URL/" "$OUT/group.png" --size 1440x900 --wait 2500 --js "(async () => { $LIB
  for (const t of ['Visitor feedback', 'Kick-off notes, Harbour & Co.', 'Quote for Harbour & Co.']) card(t).querySelector('.lc-check').click(); await wait(300);
  [...document.querySelectorAll('.lib-selbar button')].find((b) => /Group/.test(b.textContent)).click(); await wait(300);
  setv(document.querySelector('dialog[open] input'), 'Harbour & Co. pitch'); document.querySelector('dialog[open] [type=submit]').click(); await wait(1200);
  const deck = [...document.querySelectorAll('.lc.is-deck')].map((c) => c.textContent.replace(/\s+/g, ' ').trim().slice(0, 80));
  return { decks: deck, stillListed: ['Visitor feedback', 'Quote for Harbour & Co.'].filter((t) => titles().includes(t)) }; })()"

say "L1 300 more documents: the list request, first cards, typing in search, scrolling"
node scripts/seed-library.mjs "$URL" 300
echo "   GET /api/docs: $(api /api/docs -o /dev/null -w '%{size_download}') bytes for $(api /api/docs | js 'v.length') documents (before this goal: 393,854 bytes for 301)"
echo "   GET /api/library: $(api /api/library -o /dev/null -w '%{size_download} bytes in %{time_total} s'); a search: $(api '/api/library?q=kyoto' -o /dev/null -w '%{size_download} bytes in %{time_total} s')"
PERF="(async () => { $LIB
  const lcp = await new Promise((r) => new PerformanceObserver((l) => r(l.getEntries().at(-1))).observe({ type: 'largest-contentful-paint', buffered: true }));
  const frame = () => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)));
  const keys = []; const box = document.querySelector('input[aria-label=\"Search documents\"]'); let typed = '';
  for (const ch of 'lisbon') { typed += ch; const t0 = performance.now(); const before = document.querySelector('.lib-results, .lib-section')?.textContent; setv(box, typed); await frame(); const paint = performance.now() - t0;
    while (document.querySelector('.lib-results, .lib-section')?.textContent === before && performance.now() - t0 < 2000) await new Promise((r) => setTimeout(r, 5));
    keys.push({ key: ch, nextFrameMs: Math.round(paint), resultsMs: Math.round(performance.now() - t0) }); }
  const found = document.querySelectorAll('.lc').length; setv(box, ''); await wait(600);
  const pane = document.querySelector('.home'); let worst = 0, last = performance.now(), on = true;
  (function loop() { const n = performance.now(); worst = Math.max(worst, n - last); last = n; if (on) requestAnimationFrame(loop); })();
  for (let i = 0; i < 30; i++) { pane.scrollBy(0, 700); await new Promise((r) => setTimeout(r, 50)); }
  on = false; pane.scrollTo(0, 0); await wait(300);
  return { firstCardsMs: Math.round(lcp.startTime), lcpElement: lcp.element?.className, results: found, keys, scrolledCards: document.querySelectorAll('.lc').length, longestFrameWhileScrollingMs: Math.round(worst) }; })()"
shot "$URL/" "$OUT/home-300.png" --size 1440x900 --wait 3000 --js "$PERF"
shot "$URL/" "$OUT/home-300-phone.png" --size 390x844 --mobile --wait 3000 --js "$PERF"

# ───────────────────────── sharing ─────────────────────────

say "S1 a view link in a fresh browser profile: Live, no editing controls, no navigation"
shot "$URL/s/$VIEW" "$OUT/shared-view.png" --size 1440x900 --wait 3000 --js "({ editor: !!document.querySelector('.editor, .seg.mode, .inspector, .fbar'), logo: !!document.querySelector('.brand'), links: [...document.querySelectorAll('a[href]')].map(a => a.getAttribute('href')), badge: document.querySelector('.shared-badge')?.textContent.trim(), live: !!document.querySelector('.desk.live .sheet') })"
shot "$URL/s/$VIEW" "$OUT/shared-phone.png" --size 390x844 --mobile --wait 3000
shot "$URL/s/$VIEW" "$WORK/shared-dark.png" --size 1440x900 --dark --wait 3000

say "S2 a view link can't change the stored document, or reach anything else"
echo "   ops POST with the view token: HTTP $(api /api/docs/$QUOTE/ops -o /dev/null -w '%{http_code}' -XPOST -H 'content-type: application/json' -H "x-edgy-share: $VIEW" -d '{"ops":[["set","client","value","Mallory"]]}')"
echo "   client after it: $(api /api/docs/$QUOTE/read | js 'v.values.client')"
for path in /api/docs /api/library /api/docs/$OFFSITE /api/data /api/docs/$QUOTE/log; do
  echo "   GET $path with the view token: HTTP $(api $path -o /dev/null -w '%{http_code}' -H "x-edgy-share: $VIEW")"
done
echo "   token length: ${#VIEW} and ${#EDIT} characters"

say "S3 an edit link's change shows up for the owner, live (the guest's page in a frame beside the owner's editor)"
shot "$URL/d/$QUOTE?view=live" "$OUT/shared-edit-owner.png" --size 1440x900 --wait 3000 --js "(async () => { $SETV
  const f = document.createElement('iframe'); f.src = '/s/$EDIT'; Object.assign(f.style, { position: 'fixed', right: '0', top: '48px', width: '560px', height: 'calc(100vh - 48px)', border: '0', borderLeft: '4px solid #0e9f64', zIndex: 99, background: '#fff' });
  document.body.append(f); await wait(3500);
  const guest = f.contentDocument.querySelector('.sheet input[type=text]'); setv(guest, 'Grace Hopper (typed by the guest)'); guest.blur(); await wait(2000);
  return { owner: document.querySelector('.sheet input[type=text]').value, guestBadge: f.contentDocument.querySelector('.shared-badge')?.textContent.trim() }; })()"
echo "   stored client now: $(api /api/docs/$QUOTE/read | js 'v.values.client'); last change by: $(api /api/docs/$QUOTE/log | js 'v.at(-1).actor.kind')"

say "S4 a link turned off says so"
api /api/shares/$VIEW -XDELETE -o /dev/null
shot "$URL/s/$VIEW" "$OUT/unshared.png" --size 1440x900 --wait 2500 --js "document.querySelector('h1')?.textContent"
shot "$URL/s/nothing-here-$RANDOM" "$WORK/unknown-link.png" --size 1440x900 --wait 2500 --js "document.querySelector('h1')?.textContent"

# ───────────────────────── decks and Play ─────────────────────────

say "K1 the deck's page, and reordering that is kept"
api /api/decks/$DECK -XPATCH -H 'content-type: application/json' -d "{\"docs\":[\"$OFFSITE\",\"$BILLING\",\"$SAVINGS\"]}" -o /dev/null
echo "   order after a reorder and a reload: $(api /api/decks/$DECK | js 'v.items.map(d=>d.title).join(" → ")')"
shot "$URL/deck/$DECK" "$OUT/deck-page.png" --size 1440x900 --wait 2500
shot "$URL/deck/$DECK" "$OUT/deck-page-phone.png" --size 390x844 --mobile --wait 2500
shot "$URL/deck/$DECK" "$WORK/deck-page-dark.png" --size 1440x900 --dark --wait 2500
shot "$URL/deck/$DECK/play#3" "$WORK/play-dark.png" --size 1440x900 --dark --wait 3500
shot "$URL/deck/$DECK/play#3" "$WORK/play-tablet.png" --size 820x1180 --mobile --wait 3500 --js "document.querySelector('.slide-room').scrollWidth <= document.querySelector('.slide-room').clientWidth"

say "K2 Play: arrow keys, the counter, an input kept across slides, Esc back to where Play started"
shot "$URL/deck/$DECK/play?from=%2Fdeck%2F$DECK" "$OUT/play-1.png" --size 1440x900 --wait 3500 --js "(async () => { $SETV
  const i = [...document.querySelectorAll('.slide-room input[type=number]')][0]; setv(i, '22'); i.blur(); await wait(400);
  return { counter: document.querySelector('.play-count').textContent, typed: i.value }; })()" \
  --press ".slide-room|ArrowRight;;.slide-room|ArrowLeft" \
  --then "({ counter: document.querySelector('.play-count').textContent, kept: [...document.querySelectorAll('.slide-room input[type=number]')][0].value, hash: location.hash })"
for size in 1440x900 390x844; do
  mob=$([ $size = 390x844 ] && echo --mobile)
  for n in 1 2 3; do
    shot "$URL/deck/$DECK/play#$n" "$OUT/play-$size-$n.png" --size $size $mob --wait 3500 --js "(() => { const r = document.querySelector('.slide-room'); return { slide: document.querySelector('.play-count').textContent, overflowX: r.scrollWidth > r.clientWidth || document.documentElement.scrollWidth > innerWidth, scrolls: r.classList.contains('scrolls'), scale: getComputedStyle(document.querySelector('.slide-sheet')).transform } })()"
  done
done
shot "$URL/deck/$DECK/play" "$WORK/play-right.png" --size 1440x900 --wait 3500 --press ".slide-room|ArrowRight" --then "document.querySelector('.play-count').textContent + ' after →'"
shot "$URL/deck/$DECK/play" "$WORK/play-swipe.png" --size 390x844 --mobile --wait 3500 --swipe "340,130,50,140;;340,130,50,140;;60,130,350,140" --then "document.querySelector('.play-count').textContent + ' after swiping left, left, right'"
shot "$URL/deck/$DECK/play?from=%2F" "$WORK/play-esc.png" --size 1440x900 --wait 3000 --press ".slide-room|ArrowRight;;.slide-room|Escape" --then "location.pathname + location.search"

say "K1 ungrouping keeps every document"
api /api/decks/$DECK -XDELETE -o /dev/null
echo "   after ungrouping: $(for d in $OFFSITE $BILLING $SAVINGS; do api /api/docs/$d -o /dev/null -w '%{http_code} '; done)(each document still opens)"
DECK=$(api /api/decks -XPOST -H 'content-type: application/json' -d "{\"title\":\"Quarterly review\",\"description\":\"Billing, the offsite budget and the savings plan, for Friday.\",\"docs\":[\"$BILLING\",\"$OFFSITE\",\"$SAVINGS\"]}" | js v.id)

# ───────────────────────── exports ─────────────────────────

say "E1 the showcase document exported, opened from disk with the network off"
api /api/docs/$OFFSITE/export -o "$WORK/team-offsite.html"
api /api/decks/$DECK/export -o "$WORK/quarterly-review.html"
echo "   sizes: team-offsite.html $(wc -c <"$WORK/team-offsite.html") bytes, quarterly-review.html $(wc -c <"$WORK/quarterly-review.html") bytes"
echo "   external URLs in src/href/url(): $(grep -oiE '(src|href)=["'"'"']?https?:|url\(["'"'"']?https?:' "$WORK/team-offsite.html" | wc -l)"
F="file:///$(cd "$WORK" && pwd -W 2>/dev/null || pwd)"
shot "$URL/d/$OFFSITE?view=live" "$OUT/export-live.png" --size 1440x900 --wait 3000 --js "[...document.querySelectorAll('button[aria-pressed=true][title^=Activity], button[aria-pressed=true][title^=Cell]')].map((b) => (b.click(), b.title))"
shot "$F/team-offsite.html" "$OUT/export-offline.png" --size 1440x900 --offline --wait 3000 --js "(async () => { $SETV
  const total = () => [...document.querySelectorAll('.sheet *')].find(e => e.children.length === 0 && /^Total /.test(e.textContent))?.textContent;
  const before = total(); const qty = [...document.querySelectorAll('.sheet input[type=number]')].find(i => i.value === '14'); setv(qty, '20'); qty.blur(); await wait(500);
  return { before, after: total(), fonts: [...document.fonts].filter(f => f.status === 'loaded').map(f => f.family) }; })()"
# Side by side: a page that shows the two screenshots next to each other, shot like any other.
cp "$OUT/export-live.png" "$OUT/export-offline.png" "$WORK/"
printf '%s' '<!doctype html><meta charset="utf-8"><style>body{margin:0;display:flex;gap:16px;padding:16px;background:#ccc;font:600 14px sans-serif}figure{margin:0;flex:1}img{width:100%;display:block;box-shadow:0 2px 8px #0003}figcaption{padding:6px 0}</style><figure><figcaption>Live view, served by edgy</figcaption><img src="export-live.png"></figure><figure><figcaption>The exported file, opened from disk, network off (after changing a quantity)</figcaption><img src="export-offline.png"></figure>' >"$WORK/side.html"
shot "$F/side.html" "$OUT/export-side-by-side.png" --size 1600x560 --offline --wait 800

say "E2 the exported deck plays every slide, offline"
shot "$F/quarterly-review.html" "$OUT/export-deck-overview.png" --size 1440x900 --offline --wait 2500
shot "$F/quarterly-review.html" "$OUT/export-deck-play.png" --size 1440x900 --offline --wait 2500 --press ".offline-play|Enter;;.slide-room|ArrowRight;;.slide-room|ArrowRight" --then "document.querySelector('.play-count')?.textContent + ' · ' + document.querySelector('.play-title')?.textContent"
} 2>&1 | tee "$LOG"

# An agent does the same over MCP, against this server.
node $OUT/mcp-check.mjs "$URL" "$WORK" >"$OUT/mcp.txt" 2>&1; echo "mcp-check: exit $? (see mcp.txt)"

bash $P/serve.sh stop $PORT >/dev/null
